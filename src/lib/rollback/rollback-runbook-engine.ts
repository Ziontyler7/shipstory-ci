import {
  buildBlastRadiusAnalysis,
  type BlastRadiusAnalysis,
} from '../diff/blast-radius-engine.ts';
import type { MergeRequestScenario } from '../changelog/release-notes-engine.ts';

export interface RollbackStep {
  stepNumber: number;
  title: string;
  command: string;
  verificationCheck: string;
  estimatedSeconds: number;
}

export interface RollbackRunbook {
  mrIid: string;
  serviceName: string;
  commitSha: string;
  previousStableSha: string;
  estimatedRecoverySeconds: number;
  hasDatabaseDownMigrationGuard: boolean;
  gitlabCiYaml: string;
  steps: RollbackStep[];
}

export interface GitLabCiValidationResult {
  valid: boolean;
  stagesPresent: string[];
  missingStages: string[];
  hasOnFailureRollback: boolean;
  hasUnresolvedPlaceholders: boolean;
  errors: string[];
}

const REQUIRED_STAGES = [
  'validate',
  'canary_deploy',
  'blast_radius_gate',
  'auto_rollback',
];

export function generateRollbackRunbook(
  mr: MergeRequestScenario,
  blastAnalysis?: BlastRadiusAnalysis
): RollbackRunbook {
  const analysis =
    blastAnalysis ??
    buildBlastRadiusAnalysis({
      mrIid: mr.mrIid,
      title: mr.title,
      rawDiff: mr.rawDiff,
    });

  const hasDbMigration = analysis.files.some((f) => f.isSchemaMigration);
  const migrationFile =
    analysis.files.find((f) => f.isSchemaMigration)?.filePath ||
    mr.criticalTokens.find((t) => t.endsWith('.sql')) ||
    null;

  const steps: RollbackStep[] = [
    {
      stepNumber: 1,
      title: 'Freeze Canary Traffic & Drain Active Ingress Pool',
      command: `kubectl -n ${mr.environment} patch rollout ${mr.serviceName} --type merge -p '{"spec":{"paused":true}}'`,
      verificationCheck: `Confirm canary traffic weight locked at 0% on ${mr.serviceName}.`,
      estimatedSeconds: 8,
    },
    {
      stepNumber: 2,
      title: 'Revert Deployment Image to Previous Stable SHA',
      command: `git revert --no-edit ${mr.commitSha} && kubectl -n ${mr.environment} set image deployment/${mr.serviceName} app=registry.gitlab.com/transcend/${mr.serviceName}:${mr.previousStableSha}`,
      verificationCheck: `Verify all pods report image tag :${mr.previousStableSha} and Ready=1/1.`,
      estimatedSeconds: 22,
    },
  ];

  if (hasDbMigration) {
    steps.push({
      stepNumber: 3,
      title: 'Non-Destructive Database Schema Down-Migration Guard',
      command: `psql "$DATABASE_URL" -c "DROP INDEX CONCURRENTLY IF EXISTS idx_ledger_entries_idempotency_key;" # source: ${migrationFile ?? 'schema-migration'}`,
      verificationCheck:
        'Confirm zero blocked pids in pg_stat_activity and backward-compatible read/write queries.',
      estimatedSeconds: 18,
    });
  } else {
    steps.push({
      stepNumber: 3,
      title: 'Restore Runtime ConfigMap & Env Variable Snapshot',
      command: `kubectl -n ${mr.environment} rollout undo deployment/${mr.serviceName}`,
      verificationCheck: `Confirm previous ConfigMap digest active across ${mr.serviceName} replicas.`,
      estimatedSeconds: 12,
    });
  }

  steps.push({
    stepNumber: 4,
    title: 'Post-Revert Synthetic SLA & Error-Budget Probe',
    command: `curl -fsS --max-time 5 https://internal.${mr.serviceName}.svc.cluster.local/healthz?expect_sha=${mr.previousStableSha}`,
    verificationCheck: `HTTP 200 OK with commit_sha="${mr.previousStableSha}" and p99 latency within SLO.`,
    estimatedSeconds: 10,
  });

  const estimatedRecoverySeconds = steps.reduce((sum, s) => sum + s.estimatedSeconds, 0);

  const envVarsBlock =
    analysis.extractedEnvVars.length > 0
      ? analysis.extractedEnvVars
          .map((envKey) => `    ${envKey}: "\${${envKey}}"` )
          .join('\n')
      : `    SERVICE_TARGET: "${mr.serviceName}"`;

  const gitlabCiYaml = [
    `# Generated by ShipStory CI — GitLab Transcend Automated Blast-Radius & Rollback Gate`,
    `# Merge Request: ${mr.mrIid} (${mr.semverTag}) | Risk Score: ${analysis.overallRiskScore}/100 (${analysis.overallSeverity})`,
    `stages:`,
    `  - validate`,
    `  - canary_deploy`,
    `  - blast_radius_gate`,
    `  - auto_rollback`,
    ``,
    `variables:`,
    `  SERVICE_NAME: "${mr.serviceName}"`,
    `  DEPLOY_ENV: "${mr.environment}"`,
    `  CANDIDATE_SHA: "${mr.commitSha}"`,
    `  STABLE_ROLLBACK_SHA: "${mr.previousStableSha}"`,
    `  BLAST_RADIUS_SCORE: "${analysis.overallRiskScore}"`,
    ``,
    `shipstory_diff_audit:`,
    `  stage: validate`,
    `  script:`,
    `    - echo "Auditing MR ${mr.mrIid} blast radius (${analysis.overallRiskScore}/100 ${analysis.overallSeverity})..."`,
    `    - test "$BLAST_RADIUS_SCORE" -le 99`,
    ``,
    `deploy_canary_10pct:`,
    `  stage: canary_deploy`,
    `  needs: ["shipstory_diff_audit"]`,
    `  environment:`,
    `    name: ${mr.environment}`,
    `  variables:`,
    envVarsBlock,
    `  script:`,
    `    - echo "Deploying ${mr.serviceName}:${mr.commitSha} canary (10% weight) to ${mr.environment}"`,
    `    - kubectl -n "$DEPLOY_ENV" set image deployment/"$SERVICE_NAME"-canary app=registry.gitlab.com/transcend/"$SERVICE_NAME":"$CANDIDATE_SHA"`,
    ``,
    `verify_slo_blast_radius:`,
    `  stage: blast_radius_gate`,
    `  needs: ["deploy_canary_10pct"]`,
    `  script:`,
    `    - echo "Verifying downstream SLA nodes for ${mr.serviceName} (${analysis.nodes.length} graph nodes)..."`,
    `    - curl -fsS --max-time 5 "https://internal.${mr.serviceName}.svc.cluster.local/metrics/slo-gate?sha=$CANDIDATE_SHA"`,
    ``,
    `automated_emergency_rollback:`,
    `  stage: auto_rollback`,
    `  needs: ["verify_slo_blast_radius"]`,
    `  when: on_failure`,
    `  environment:`,
    `    name: ${mr.environment}`,
    `  script:`,
    `    - echo "SLO gate failed for ${mr.commitSha}! Executing deterministic rollback to ${mr.previousStableSha}..."`,
    ...steps.map((s) => `    - ${s.command.replace(/"/g, '\\"')}`),
    ``,
    `manual_one_click_rollback:`,
    `  stage: auto_rollback`,
    `  when: manual`,
    `  allow_failure: true`,
    `  environment:`,
    `    name: ${mr.environment}`,
    `  script:`,
    `    - echo "Operator triggered 1-click rollback to ${mr.previousStableSha}"`,
    `    - kubectl -n "$DEPLOY_ENV" set image deployment/"$SERVICE_NAME" app=registry.gitlab.com/transcend/"$SERVICE_NAME":"$STABLE_ROLLBACK_SHA"`,
  ].join('\n');

  return {
    mrIid: mr.mrIid,
    serviceName: mr.serviceName,
    commitSha: mr.commitSha,
    previousStableSha: mr.previousStableSha,
    estimatedRecoverySeconds,
    hasDatabaseDownMigrationGuard: hasDbMigration,
    gitlabCiYaml,
    steps,
  };
}

export function verifyGitLabCiYamlSyntax(runbook: RollbackRunbook): GitLabCiValidationResult {
  const yaml = runbook.gitlabCiYaml;
  const errors: string[] = [];

  const stagesPresent = REQUIRED_STAGES.filter((st) =>
    new RegExp(`^\\s*-\\s*${st}\\b`, 'm').test(yaml)
  );
  const missingStages = REQUIRED_STAGES.filter((st) => !stagesPresent.includes(st));
  if (missingStages.length > 0) {
    errors.push(`Missing required GitLab CI stage(s): ${missingStages.join(', ')}`);
  }

  const hasOnFailureRollback =
    /automated_emergency_rollback:[\s\S]*?when:\s*on_failure/m.test(yaml);
  if (!hasOnFailureRollback) {
    errors.push('Missing `when: on_failure` directive on automated_emergency_rollback job.');
  }

  const hasUnresolvedPlaceholders =
    /\{\{.*?\}\}|\bundefined\b|\bNaN\b/.test(yaml);
  if (hasUnresolvedPlaceholders) {
    errors.push('Detected unresolved template placeholder or undefined value in .gitlab-ci.yml.');
  }

  if (!yaml.includes(runbook.commitSha) || !yaml.includes(runbook.previousStableSha)) {
    errors.push('Rollback YAML is missing candidate or stable rollback commit SHA.');
  }

  return {
    valid: errors.length === 0,
    stagesPresent,
    missingStages,
    hasOnFailureRollback,
    hasUnresolvedPlaceholders,
    errors,
  };
}
